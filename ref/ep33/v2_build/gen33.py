def main():
    fs = {}
    for g in ('G1', 'G2', 'G3', 'G4', 'G5', 'G6', 'R1', 'R2'):
        for f in json.load(open(os.path.join(AG, 'findings_%s.json' % g), encoding='utf-8')):
            fs[f['id']] = f
    text = blocks_v1()
    pats = []
    for fid, cut in TAKE:
        f = fs[fid]
        old, new = f.get('fix_old') or '', f.get('fix_new') or ''
        if not old or not new:
            raise SystemExit('🔴 %s に直しの案が無い' % fid)
        pats.append(dict(cut=cut, old=old, new=new, why=(f.get('problem') or '')[:160], frm=[fid]))
    pats += CUSTOM
    pats.append(reorder_cb(text))
    # 並び＝§4 のカットの順（§ と * は後ろ・同じカットの中は書いた順）
    order = re.findall(r'^\*\*(c[0-9a-c]\d{2})\*\*', text[text.index('## 4. 台本'):text.index('\n## 5.')], re.M)
    rank = {c: i for i, c in enumerate(order)}
    def key(p):
        if p['cut'] == '*':
            return (rank['cb12'], 0)
        if p['cut'] == '§':
            return (10000, 0)
        return (rank[p['cut']], 1)
    pats = sorted(enumerate(pats), key=lambda ip: (key(ip[1]), ip[0]))
    out = []
    for k, (_, p) in enumerate(pats, 1):
        out.append({'id': 'V2-%03d' % k, 'cut': p['cut'], 'old': p['old'], 'new': p['new'], 'why': p['why'], 'from': p['frm']})
    # 所見の数え（どれか1つに入るか）
    used = {}
    for p in out:
        for f in p['from']:
            used.setdefault(f, []).append(p['id'])
    miss = [f for f in fs if f not in used and f not in OVR]
    dup = [f for f in OVR if f in used]
    unknown = [f for f in list(used) + list(OVR) if f not in fs]
    ovr = {f: {'d': d, 'why': w} for f, (d, w) in OVR.items()}
    for f, w in PART.items():
        ovr[f] = {'d': '一部', 'why': w}
    print('差し替え %d件（係の案をそのまま %d・④\' の字 %d・並べ替え 1）・扱いの上書き %d' % (len(out), len(TAKE), len(CUSTOM), len(ovr)))
    print('所見 %d件：差し替えに入った %d・上書き %d・漏れ %d %s・二重 %d %s・知らない id %d %s' % (
        len(fs), len(used), len(OVR), len(miss), ' '.join(miss), len(dup), ' '.join(dup), len(unknown), ' '.join(unknown)))
    if miss or dup or unknown:
        return 1
    if '--check' in sys.argv:
        return 0
    json.dump(out, open(os.path.join(HERE, 'patches33.json'), 'w', encoding='utf-8', newline='\n'), ensure_ascii=False, indent=1)
    json.dump(ovr, open(os.path.join(HERE, 'ledger_ovr.json'), 'w', encoding='utf-8', newline='\n'), ensure_ascii=False, indent=1)
    print('→ v2_build/patches33.json・v2_build/ledger_ovr.json')
    return 0


