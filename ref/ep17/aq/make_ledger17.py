bad = [b for b in bad if b != "310"]
assert not bad, f"下書きの ✕ が DROP に無い（読まずに通そうとしている）: {bad}"
out = [ln if not ln.startswith("310\t") else "310\tさんいちまる\t" + NOTE["310"] for ln in out]
(AQ / "numbers.tsv").write_text("\n".join(out) + "\n", encoding="utf-8")
