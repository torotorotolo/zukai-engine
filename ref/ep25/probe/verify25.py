def norm(s):
    return re.sub(r"\s+", "", unicodedata.normalize("NFKC", s))


def main():
    src, out = sys.argv[1], sys.argv[2]
    docs = {}
    for p in glob.glob(os.path.join(src, "txt", "*.json")):
        docs[os.path.splitext(os.path.basename(p))[0]] = json.load(open(p, encoding="utf-8"))
    lines = []
    for key, name, page, words in CLAIMS:
        d = docs.get(name)
        lines.append(f"### {key} {name} ①の頁={page}")
        if d is None:
            lines.append("  !! 資料なし")
            continue
        for w in words:
            nw = norm(w)
            hits = []
            for pg in d:
                t = pg["norm"]
                for m in re.finditer(re.escape(nw), t):
                    a, b = max(0, m.start() - CTX), min(len(t), m.end() + CTX)
                    hits.append((pg["printed"], pg["pdf"], t[a:m.start()] + "【" + t[m.start():m.end()] + "】" + t[m.end():b]))
            pages = sorted({h[0] for h in hits if h[0] is not None})
            lines.append(f"  [{w}] 件数={len(hits)} 印刷頁={pages[:25]}{' …' if len(pages) > 25 else ''}")
            for h in hits[:3]:
                lines.append(f"     p{h[0]}(PDF{h[1]}) {h[2]}")
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("done", len(CLAIMS))


if __name__ == "__main__":
    main()
