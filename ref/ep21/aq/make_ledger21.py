out = ["# 21本目 9.11 米国同時多発テロ（リメイク）⑤a-1：数の台帳（tools/check_aq_yomi.py が読む）。鍵<TAB>読み<TAB>注",
       "# 作り方＝利用者辞書を入れたあとの check_aq_yomi --propose の下書き（pyopenjtalk の読み）を、台本 §6・§9・§1-5 と日本語の標準の読みを",
       "#   答えに Claude が1鍵ずつ読んだ（2026-10-12）。辞書の前の下書きは、カンマで割れた読みも 767・757・7人・37人・0分 も ○ で通していた",
       f"# 直した鍵＝切り方の誤り・語だけの読みの違い {len(DROP)} を外し、ADD の {len(ADD)} 鍵に置き換えた（make_ledger21.py の表）",
       "# ⚠️ 読みは長音を「ー」で書く（音声記号列の書き方）。鍵は台本の字のまま（算用数字は半角・NFKC）"]
seen = set()
for k, r, flag, lines in draft:
    if k in DROP:
        continue
    note = NOTE.get(k) or (COMMA if "," in k else f"下書きのまま（{lines.split(',')[0]}）")
    out.append(f"{k}\t{r}\t{note}")
    seen.add(k)
for k, r, note in ADD:
    assert k not in seen, k
    out.append(f"{k}\t{r}\t{note}")
missing = DROP - {d[0] for d in draft}
assert not missing, f"DROP の鍵が下書きに無い: {missing}"
bad = [d[0] for d in draft if d[2] != "○" and d[0] not in DROP]
assert not bad, f"下書きの ✕ が DROP に無い（読まずに通そうとしている）: {bad}"
(AQ / "numbers.tsv").write_text("\n".join(out) + "\n", encoding="utf-8")
