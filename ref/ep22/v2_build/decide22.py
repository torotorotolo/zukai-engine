def main():
    fs = {}
    for f in sorted(glob.glob(os.path.join(HERE, 'findings_G*.json'))) + sorted(glob.glob(os.path.join(HERE, 'review_R*.json'))):
        for x in json.load(open(f, encoding='utf-8')):
            fs[x['id']] = x
    out, bad = {}, []
    for pid, x in fs.items():
        if pid in OVR:
            o = OVR[pid]
            d = {'v': o[0], 'note': o[1]}
            if len(o) > 2:
                d.update(o[2])
        else:
            if not (x.get('new') or '').strip():
                bad.append(pid)
                continue
            d = {'v': '採る', 'note': DEFAULT_NOTE}
        if pid in SUB and d['v'] == '採る' and 'new' not in d:
            new = x['new']
            for a, b in SUB[pid]:
                new = new.replace(a, b)
            d['new'] = new
        out[pid] = d
    unknown = sorted(set(OVR) - set(fs))
    if bad or unknown:
        print('🔴 new が空なのに決めが無い:', bad, '／OVR にあるのに所見が無い:', unknown)
        sys.exit(1)
    json.dump(out, open(os.path.join(HERE, 'decisions22.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=0)
    patches = [{'id': g['id'], 'cut': g['cut'], 'old': g['old'], 'new': g['new'], 'why': g['what']} for g in G0]
    json.dump(patches, open(os.path.join(HERE, 'patches_g0.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=0)
    json.dump([dict(g, v='採る', note='G0 の直し') for g in G0], open(os.path.join(HERE, 'g0_ledger.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=0)
    cnt = {}
    for d in out.values():
        cnt[d['v']] = cnt.get(d['v'], 0) + 1
    print('decisions22.json %d件 %s／G0 %d件' % (len(out), cnt, len(G0)))


if __name__ == '__main__':
    main()
