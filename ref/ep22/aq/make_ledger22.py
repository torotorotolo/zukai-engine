# -*- coding: utf-8 -*-
"""22本目の数の台帳を、下書き（check_aq_yomi --propose）＋人が決めた直しの表から組む（2026-10-14・⑤a-1）。
下書きの鍵は1つずつ読んで確かめた（読み一覧の行と標準の読み・台本 §6・§9・§1-5）。直したのは下の DROP と ADD だけ。
21本目の `ref/ep21/aq/make_ledger21.py` を写した（表だけ22本目のもの）。

  python tools/check_aq_yomi.py --propose 2>/dev/null | grep -v "^Warning\\|^Please install" > ref/ep22/aq/numbers_draft.tsv
  python ref/ep22/aq/make_ledger22.py      … numbers_draft.tsv ＋ 下の表 → numbers.tsv（書き換える）
⚠️ 下書きは利用者辞書 userdict.csv を入れたあとに作り直したもの。辞書の前の下書きは、カンマの数18種（約3,800メートル＝
   さん、はっぴゃく…・6,000メートル＝ろく、ぜろぜろぜろ…）・1都6県（いちと/ろくけん）・27時間（にじゅうしちじかん）を「○」で通していた
   （同じ変換器の写し）
⚠️ 台本の数が変わったら、下書きを作り直し、新しい鍵を1つずつ読んでからここの表を直す（下書きの「○」は変換器の写し）"""
from pathlib import Path

AQ = Path(__file__).resolve().parent
draft = [ln.split("\t") for ln in (AQ / "numbers_draft.tsv").read_text(encoding="utf-8").splitlines()[1:] if ln.strip()]

# 下書きの鍵のうち、切り方が誤っている（後ろの字を余計に拾った・数の頭だけ拾った・語だけの読みが違う）もの → 外して ADD で置き換える
DROP = {"133枚重", "24人乗", "9回触", "4回受",      # 後ろの字（動詞の頭）まで拾った
        "2",                                        # 数の頭だけ拾った（か所が抜けた）
        "11", "3分", "1都", "6県"}                  # 語だけの読みが違う（✕要確認）＝前後の字ごと鍵に
ADD = [
    ("133枚", "ひゃくさんじゅーさんまい", "下書きは「133枚重」＝重 まで拾った（c906-1「膜を133枚重ねたもの」＝文の中は かさねた）"),
    ("24人", "にじゅーよにん", "下書きは「24人乗」（c302-2「乗客に数えられる人が24人乗っていた」＝文の中は のっていた）"),
    ("9回", "きゅーかい", "下書きは「9回触」（c209-3「「死」に9回触れていた」）"),
    ("4回", "よんかい", "下書きは「4回受」（c921-1「4,000メートル前後の加圧を4回受け」）"),
    ("2か所", "にかしょ", "下書きは「2」だけ（c610-3「接着の面は2か所だった」）"),
    ("11か月", "じゅーいっかげつ", "下書きは「11」だけ＝語だけの読みは じゅーいち（c104-1「その11か月前」・ca26-3「11か月を過ごす」）"),
    ("3分の1", "さんぶんのいち", "下書きは「3分」＝語だけの読みは さんぷん（c711-1・c903-2「3分の1の模型」＝文の中は さんぶんの）"),
    ("1都6県", "いっとろっけん", "辞書 １都６県（変換器は いちと/ろくけん・c510-2）＝台本 §6「いっとろっけん」"),
]
COMMA = "桁区切りのカンマ＝辞書で直した（変換器は「さん、はっぴゃく」「ろく、ぜろぜろぜろ」と割る＝ルール 5a-26・下書きは辞書の前も ○ で通した）"
NOTE = {
    "27時間": "にじゅうななじかん＝辞書 ２７時間（変換器は にじゅうしちじかん・c215-2＝同じ回の「27回」c212-2 は なな）",
    "1万": "c709-1「約1万3,200メートル」の万の上（下の 3,200メートル は辞書）",
    "4万": "c510-1「約4万1,000平方キロ」の万の上（下の 1,000平方キロ は辞書）",
    "700": "c219-2「約700〜800キロ」＝「〜」を変換器が落とした＝手書き override（ななひゃくから）",
    "1": "c707-3「1より大きい」・c711-1・c903-2「3分の1」の 1",
    "0.5度": "cb04-1「マイナス0.5度」＝れいてんご（台本 §9）",
    "5.4秒後": "c413-3「その約5.4秒後」＝台本 §6「ごてんよんびょう」",
    "26.9秒": "c413-3「10時47分26.9秒」＝台本 §6",
    "7月": "しちがつ", "9月": "くがつ", "9時": "くじ", "19日": "じゅうくにち", "24日": "にじゅうよっか", "3日": "みっか",
    "4日前": "よっかまえ", "4日後": "よっかご", "5日": "いつか", "6日": "むいか", "1人最大": "ひとり さいだい（c210-2）",
}
out = ["# 22本目 タイタン号（リメイク）⑤a-1：数の台帳（tools/check_aq_yomi.py が読む）。鍵<TAB>読み<TAB>注",
       "# 作り方＝利用者辞書を入れたあとの check_aq_yomi --propose の下書き（pyopenjtalk の読み）を、台本 §6・§9・§1-5 と日本語の標準の読みを",
       "#   答えに Claude が1鍵ずつ読んだ（2026-10-14）。辞書の前の下書きは、カンマで割れた読み18種も 1都6県・27時間 も ○ で通していた",
       f"# 直した鍵＝切り方の誤り・語だけの読みの違い {len(DROP)} を外し、ADD の {len(ADD)} 鍵に置き換えた（make_ledger22.py の表）",
       "# ⚠️ 読みは長音を「ー」で書く（音声記号列の書き方）。鍵は台本の字のまま（算用数字は半角・NFKC）"]
seen = set()
for k, r, flag, lines in draft:
    if k in DROP:
        continue
    note = NOTE.get(k) or (COMMA if "," in k else f"下書きのまま（{lines.split(',')[0]}）")
    out.append(f"{k}\t{r}\t{note}")
    seen.add(k)
for k, r, note in ADD:
    assert k not in seen, k
    out.append(f"{k}\t{r}\t{note}")
missing = DROP - {d[0] for d in draft}
assert not missing, f"DROP の鍵が下書きに無い: {missing}"
bad = [d[0] for d in draft if d[2] != "○" and d[0] not in DROP]
assert not bad, f"下書きの ✕ が DROP に無い（読まずに通そうとしている）: {bad}"
(AQ / "numbers.tsv").write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"台帳 {len(out) - 5}鍵（下書き {len(draft)} − 外した {len(DROP)} ＋ 足した {len(ADD)}）")
