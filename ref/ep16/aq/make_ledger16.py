    ("30分足らず", "さんじゅっぷんたらず", "下書きは「30分足」＝足を あし と読む鍵（行の読みは たらず で正しい・c310-1）"),
    ("45秒足らず", "よんじゅーごびょーたらず", "同上（c806-1）"),
    ("8階建て", "はっかいだて", "下書きは「8階建」＝建を けん と読む鍵（行の読みは だて で正しい・c515-1）"),
    ("8か月", "はっかげつ", "「8」だけの鍵では はち が無く ✕（c309-3・ca22-2「3年8か月」）。「反対8」（ca03-1）は「8」＝はち"),
    ("3,000万立方メートル", "さんぜんまんりっぽーめーとる", "桁区切りのカンマ＝辞書で直した（c816-1・c819-1）"),
    ("5,000万立方メートル", "ごせんまんりっぽーめーとる", "同上（c206-1「1億5,000万」・c422-2）"),
    ("7,000万立方メートル", "ななせんまんりっぽーめーとる", "同上（c804-1「2億7,000万」）"),
    ("3回", "さんかい", "下書きは「3回出」"),
    ("300倍", "さんびゃくばい", "下書きは「300倍近」"),
    ("1立方メートル", "いちりっぽーめーとる", "下書きは「1立方メー」"),
    ("2億立方メートル", "におくりっぽーめーとる", "下書きは「2億立方メ」"),
    ("3億立方メートル", "さんおくりっぽーめーとる", "下書きは「3億立方メ」"),
    ("70万立方メートル", "ななじゅーまんりっぽーめーとる", "下書きは「70万立方メ」"),
