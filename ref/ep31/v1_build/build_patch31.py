def main(fj, md, out):
    d = json.load(open(fj, encoding='utf-8'))
    text = open(md, encoding='utf-8').read()
    rows = {'%s%02d' % (r['ag'], r['k']): r for r in d['rows']}
    pairs = []
    for key in ACCEPT:
        r = rows[key]
        if not r['fix_old']:
            print('🔴 直しの無い所見を採った:', key)
            return 1
        pairs.append((key, r['fix_old'], r['fix_new']))
    for i, (o, n) in enumerate(CUSTOM, 1):
        pairs.append(('親%02d' % i, o, n))
    bad, spans = [], []
    for key, o, n in pairs:
        c = text.count(o)
        if c != 1:
            bad.append('%s 元の文が %d回: %s' % (key, c, o[:60].replace('\n', '⏎')))
            continue
        s = text.find(o)
        spans.append((s, s + len(o), key))
    spans.sort()
    for (s0, e0, k0), (s1, e1, k1) in zip(spans, spans[1:]):
        if s1 < e0:
            bad.append('重なり %s × %s' % (k0, k1))
    if bad:
        print('🔴 止めた（表を書かない）')
        for b in bad:
            print(' ', b)
        return 1
    json.dump([[o, n] for _, o, n in pairs], open(out, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print('表 %d件（係の案 %d・親 %d）→ %s' % (len(pairs), len(ACCEPT), len(CUSTOM), out))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1], sys.argv[2], sys.argv[3]))
