def main():
    """🔴 割り当てそのものを検算する。前のチャットの主張は使わない。"""
    import collections
    import json
    import sys
    from pathlib import Path
    here = Path(__file__).resolve().parents[1]
    sys.stdout.reconfigure(encoding='utf-8', errors='replace')
    plan = json.loads((here / 'qa_out/ep10_cuts_plan.json').read_text(encoding='utf-8'))
    db = json.loads((here / 'ref/ep10/assets.json').read_text(encoding='utf-8'))
    ok = True

    def chk(name, good, detail=''):
        nonlocal ok
        ok &= good
        print(f"  {'✓' if good else '🔴'} {name}{('  ' + detail) if detail else ''}")

    want = {c for c, v in plan.items() if v['kind'] == 'photo'}
    chk('写真カット全部に点が付いている', set(A) == want,
        f'台本 {len(want)} ／ 割り当て {len(A)} ／ 差 {sorted(set(A) ^ want)}')
    chk('知らない点を当てていない', all(v[0] in db for v in A.values()),
        f'{sorted(v[0] for v in A.values() if v[0] not in db)}')
    use = collections.Counter(v[0] for v in A.values())
    sa_dup = {p: n for p, n in use.items() if n > 1 and db[p]['share_alike']}
    chk('額装縛り（BY-SA）の点を2回以上使っていない', len(sa_dup) <= 2,
        f'2回出す点 {sorted(sa_dup)}（同じ絵がそのまま出る。3件以上なら見直す）')
    free_dup = {p: n for p, n in use.items() if n > 1 and not db[p]['share_alike']}
    print(f'  ・ 手直し可の点の使い回し（寄りを変えるので可）: '
          f'{ {p: n for p, n in sorted(free_dup.items())} }')
    bad_mode = [c for c, v in A.items() if db[v[0]]['share_alike'] and v[1] != 'frame']
    chk('BY-SA の点を frame 以外で出していない', not bad_mode, f'{bad_mode}')
    admin = ('c319', 'c905', 'c913', 'c915', 'ep01', 'ep02', 'ep04', 'ep06', 'ep08')
    bags = ('site_cleanup_02', 'site_cleanup_06', 'rescue_work_19')
    hit = [c for c in admin if A[c][0] in bags]
    chk('事務・補償・裁判のカットに「袋が写る点」を当てていない', not hit, f'{hit}')
    chk('理由が全部書いてある', all(v[2] for v in A.values()))
    print(f'\n  使った点 {len(use)} ／ 在庫 {len(db)} ／ 使わなかった {len(db) - len(use)}点: '
          f'{sorted(set(db) - set(use))}')
    print('\n' + ('✓ 割り当ては通った' if ok else '🔴 割り当てに穴がある'))
    return 0 if ok else 1


if __name__ == '__main__':
    raise SystemExit(main())
