def check(plan):
    import el_script as ES
    ls = ES.lines()
    by = {l.lid: l for l in ls}
    bad, out = [], []
    rules = {}
    for ids, key, val, why in plan:
        if key in rules and rules[key] != val:
            bad.append(f"同じ key「{key}」に別の val")
        rules[key] = val
        if val.count("、") > key.count("、"):
            bad.append(f"④ 「{key}」の val に読点を足している: {val}")
    order, pats = ES._compile_yomi(rules)
    eff, per_line, final = {}, {}, {}
    for l in ls:
        h = []
        final[l.lid] = ES.apply_yomi(ES.el_text(l.text), order, pats, rules, h)
        for k, _v, _n in h:
            eff.setdefault(k, set()).add(l.lid)
            per_line.setdefault(l.lid, []).append(k)
    for ids, key, val, why in plan:
        if set(ids) != eff.get(key, set()):
            bad.append(f"③ 「{key}」の本当に当たる行 {sorted(eff.get(key, set()))} ≠ 計画 {sorted(ids)}")
        for lid in ids:
            ln = by.get(lid)
            if ln is None:
                bad.append(f"① 台本に無い行ID: {lid}")
                continue
            sent = ES.el_text(ln.text)
            if key not in sent:
                bad.append(f"② {lid}: 「{key}」が送信文に無い → {sent}")
                continue
            ab = sent.replace(key, val)
            if ab != final[lid]:
                bad.append(f"⑤ {lid}: A/B の文字列と本番の文字列が違う\n      A/B : {ab}\n      本番: {final[lid]}")
            head = "  ⚠️行頭がかな" if (ab[:1] != sent[:1] and "ぁ" <= ab[:1] <= "ヿ") else ""
            print(f"  {lid:<8}「{key}」→「{val}」{head}")
            out.append({"id": lid, "key": key, "val": val, "why": why})
    for lid, keys in per_line.items():
        if len(keys) > 1:
            bad.append(f"⑥ {lid} に {len(keys)} キーが当たる: {keys}（長いキー1つにまとめる）")
    return out, bad


