# -*- coding: utf-8 -*-
"""240カットの「画」の割り当て。章ごとにファイルを分けてある。

■ 直すところ
  図を変えたいときは、その章のファイルの1カットぶんの dict だけを直す。
  `tools/titan_fig.py` の型を増やすのは、**同じ形が3カット以上で要るときだけ**。

■ 1カットの書き方
    "c103": dict(
        t="乗っていたのは42人",              # 見出し（左上・Dela 62px）
        s="ポーラープリンス　2023年6月18日",   # 副題（省略可）
        fig=("breakdown", dict(total=42, parts=[...])),
    )
  実写カットは fig の代わりに photo を書く：
    "pr01": dict(t="…", s="…", photo="surfside/tf_p003_model.jpg", bias=0.5, side="right",
                 ann=[dict(t="高さ", v="33.8 m")])

■ 守ること
  1 **ナレーションの文を図にそのまま書かない。** 図が持つのは数値・部位名・関係。
    引用カットは「言葉」ではなく**出どころ**（誰が・誰に・いつ・どこに）を図にする。
  2 見出しは 22 字まで（Dela 62px で 1,364px。RIGHT=1848 に収まる）。
  3 段（figの stages）の数は**ナレーションの行数に近づける**。
    行より多い段は行の間に挟まれる。少ない場合は最後の段が長く描かれる。

■ 🔴 2026-09-05：**4本目（サーフサイド）へ差し替え。**
  カットIDは題材をまたいでぶつかる（3本目 241カットのうち大半が同じID）。
  3本目（スレッシャー号）の章ファイル・PHOTO_OVERRIDE・BACKDROP は git の `ad6882a` にある。
  検算：`python -c "import cuts; print(len(cuts.SPEC))"` が**台本のカット数（240）**であること。
"""
import importlib
import sys

import jiko_style as J

# 章ごとに1ファイル。**1章が壊れていても他章は読めるようにする**
# （章を並行して書いているあいだ、片方の書きかけで全部の検査が止まらないように）。
# 🔴 5本目（SL-1）は 冒頭＋**9章**＋締め（台本第2版 §3）。4本目は7章なので c8・c9 を足した。
CHAPTER_FILES = ("pr", "c1", "c2", "c3", "c4", "c5", "c6", "c7", "c8", "c9", "ep")

SPEC = {}
BROKEN = {}
for _name in CHAPTER_FILES:
    try:
        _m = importlib.import_module(f".{_name}", __name__)
        _dup = set(SPEC) & set(_m.SPEC)
        if _dup:
            raise RuntimeError(f"カットIDが重複しています: {sorted(_dup)}")
        SPEC.update(_m.SPEC)
    except Exception as e:                      # noqa: BLE001
        BROKEN[_name] = e
        print(f"⚠️ cuts/{_name}.py を読めませんでした: {e}", file=sys.stderr)


# ══════════════════════════════════════════════════════════
#  写真に差し替えるカット（図の代わりに写真そのものを出す）
# ══════════════════════════════════════════════════════════
# **どのカットを写真にするかは章をまたぐ編集判断**なので、章ファイルではなくここに置く。
# 章ファイル側の図の定義はそのまま残るので、ここから消せば図に戻る。
#
# 🔴 2026-09-05：**3本目（スレッシャー号）の割り当てを全部捨てた。** 中身は git の `ad6882a`。
#    4本目は、写真カットを**章ファイルに直接 `photo=` で書いてある**（台本 §4 の画の欄と1対1で
#    照合できるように）。ここは空のまま。上書きが要る判断が出たときだけ使う。
PHOTO_OVERRIDE = {
}

for _cid, _ov in PHOTO_OVERRIDE.items():
    if _cid not in SPEC:
        continue
    _keep = {k: SPEC[_cid][k] for k in ("t", "s") if k in SPEC[_cid]}
    SPEC[_cid] = dict(_keep, **_ov)


# ══════════════════════════════════════════════════════════
#  ★写真を「地」に敷いて、その上に図解を重ねるカット
# ══════════════════════════════════════════════════════════
# `photo` と `fig` を**両方**持たせると、写真が地になり、暗幕を挟んで図が乗る。
# （上の PHOTO_OVERRIDE は図を写真に**差し替える**。こちらは図を**残す**。）
#
# ⚠️ **全カットに敷かない。** 敷いた瞬間に「図解チャンネル」である意味が消える。
#    競合との差は図があることなので、退屈になりやすいカットだけに絞る。
#
# 🔴 選び方の原則（このチャンネルの性格＝一次資料で検証する、を壊さないため）
#    **その写真が、そのカットで話している対象そのものであること。**
#    「時刻の札の後ろに、関係のない残骸の写真を壁紙として敷く」のはやらない。
#    出典表記は地に敷いた場合も必ず出す（`fig_base(ground=False)` が出す）。
#
# 🔴 2026-09-05：**3本目の割り当てを全部捨てた**（git `ad6882a`）。
#    4本目は写真映像が 122/240（50.8%）あり、台本 §5 の数え方は「実写」と「図 pNN」の
#    2種だけで満たしている。**地に敷く割り当ては、⑤c の目視で「平板」と出たカットにだけ足す。**
#    ⚠️ 付図・線図（p36・p139・自作の模式図）は地に敷かない（白地の細い線は暗幕で沈む）。
# ══════════════════════════════════════════════════════════
# 🔴🔴 2026-09-13（7本目 ⑤b-2）**6カットに敷いた。理由は割合ではなく、絵の中身。**
# ══════════════════════════════════════════════════════════
#   ⑤b-2 で、台本が「実写」と決めていた **12カット**を図に振り替えた。
#   権利の使える範囲に、その欄の中身を写した写真が**1点も無かった**ためで、
#   よその建物・よその制御室で代用するのは「写っていないものを名乗る」ことになる
#   （[[feedback-subtitle-must-match-what-is-visible]]）。
#     c212 c406 c606 c502 … 管制センター4施設の**建物そのもの**の写真が無い
#     c310 c408 c603      … 航空会社の**運航管理室**の写真が無い
#     c712                … **戦闘機の航跡**が写ったクリップが無い
#     c903                … **強化された扉**と分かる写真が無い
#     pr07 c813 c817      … **報告書そのもの**の写真が無い
#   → 写真映像が 98 → 86カット（42.6%）になり、規則 45〜50% を下回る。
#
# 🔴 そこで、**写真が「そのカットで話している対象そのもの」になる図解6枚**に地を敷いた。
#    ⚠️ 割合を作るために敷いたのではなく、**敷いてよい条件を満たす6枚を選んだ**。
#       条件を満たさないカット（時刻の札・人の道すじ・まとめ）には1枚も敷いていない。
#    → 86 + 6 = **92カット（45.5%）**。
#    ⚠️ ⑤c の目視で「地が図を邪魔している」と出たら、ここから消せば図だけに戻る。
BACKDROP = {
    # 高さの図の地に、その建物そのもの
    "c216": dict(photo="ep7/wtc_twin.jpg", bias=0.30, xbias=0.50, zoom=1.10),
    "c217": dict(photo="ep7/wtc_far.jpg", bias=0.34, xbias=0.50, zoom=1.10),
    # 1993年の爆破の図の地に、その建物そのもの
    "c802": dict(photo="ep7/wtc_base.jpg", bias=0.46, xbias=0.50, zoom=1.08),
    # 刃物の線の図の地に、当時の保安検査場
    "c113": dict(photo="ep7/security_pre.jpg", bias=0.44, xbias=0.50, zoom=1.12),
    # 検査の担い手の図の地に、いまの検査場
    "c902": dict(photo="ep7/security_now.jpg", bias=0.48, xbias=0.50, zoom=1.06),
    # 管制の仕事ぶりを評価した図の地に、管制の卓
    "c519": dict(photo="ep7/artcc_screen2.jpg", bias=0.46, xbias=0.50, zoom=1.06),
}

for _cid, _ov in BACKDROP.items():
    if _cid not in SPEC:
        print(f"⚠️ BACKDROP の {_cid} が台本にありません", file=sys.stderr)
        continue
    if "fig" not in SPEC[_cid]:
        raise RuntimeError(f"{_cid} は図を持っていないので地に敷けません（実写カット）")
    SPEC[_cid] = dict(SPEC[_cid], **_ov)
