    k = DR_OPEN if st["door"] == "open" else 1.0
    sk = 26.0 if st["door"] == "open" else 0.0
    w0 = dx1 - dx0

    def P(x, y):
        u = (x - dx0) / w0                                  # 蝶番からの割合（0＝蝶番・1＝取っ手の側）
