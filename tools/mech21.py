def _plane_top(cx, cy, L, col=None, ln=None, fighter=False, dash=None, op=None):
    """上から見た機（機首が右・L＝長さの画素）。fighter＝戦闘機（細い胴・後退翼・2枚の尾翼）。"""
    c, k = col or COL["body"], ln or COL["body_ln"]
