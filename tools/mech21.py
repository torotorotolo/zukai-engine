            out["routes"] = [(a, b) for _, a, b in ROUTES]
            out["flights"] = {k: US_FLT[k] for k in US_FLT}
            out["air"] = [G.px(*p) for p in AIR_PTS]                          # 🆕 ⑤b-4：空港の点の画素
