    print(f"\n最長の字幕 = {worst[0]:.2f}秒「{worst[1]}」")
    print("✓ 3秒以下" if worst[0] <= 3.0 else "🔴 まだ3秒を超えている")
    return 0 if worst[0] <= 3.0 else 1


