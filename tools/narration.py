def synth(text):
    """1行ぶんを合成して (wavバイト列, 秒, かな) を返す。"""
    q = json.loads(post("audio_query", None,
                        f"speaker={SPEAKER}&text={urllib.parse.quote(text)}").read())
    q["speedScale"] = SPEED
    wav = post("synthesis", q, f"speaker={SPEAKER}").read()
    import io
    with wave.open(io.BytesIO(wav)) as w:
        sec = w.getnframes() / w.getframerate()
        p = (w.getnchannels(), w.getsampwidth(), w.getframerate())
        frames = w.readframes(w.getnframes())
    return frames, p, sec, kana_of(q)


def _sig(lines):
    """カットの内容の指紋。1文字でも変われば別物として作り直す。"""
    # 🔴 2026-08-01 修正。**台本の生の文字だけを見ていたのが誤りだった。**
    #    エンジンへ渡るのは apply_yomi() を通したあとの文字列なので、
    #    **台本が同じでも YOMI を直せば音は変わる**。ところが指紋は変わらないため
    #    `build resume` が「変更なし」と判断し、**古い音声をそのまま残していた。**
    #    2026-08-01、`潜らせた` と `2.25` の読みを直したときに実際に踏んだ
    #    （直したつもりで、古い音のまま焼くところだった）。
    #    → 指紋は**実際にエンジンへ渡る文字列**から取る。
    import hashlib
    spoken = "".join(apply_yomi(x) for x in lines)
    return hashlib.sha1((spoken + f"|{SPEAKER}|{SPEED}|{GAP}").encode()).hexdigest()[:12]


def build(resume=False):
    """resume=True なら**内容が変わっていないカットの wav を作り直さない**。

    🔴 2026-07-31 追加。1本ぶんの合成は30分かかるので、台本を1行直すたびに
    30分待つのは現実的でない。`narration.json` に各カットの指紋を書いておき、
    指紋が一致して wav も残っているカットは、前回の尺と字幕をそのまま持ち越す。
    """
    out = HERE / "audio"
    out.mkdir(exist_ok=True)
    prev, old_sig = {}, {}
    if resume and (out / "narration.json").exists():
        prev = json.loads((out / "narration.json").read_text(encoding="utf-8"))
        old_sig = prev.get("signatures", {})
    durs, subs, sigs, bad, longest = {}, {}, {}, 0, (0.0, "")
    # かなログも持ち越す。作り直したカットだけ新しくして、残りは前回の記録を引き継ぐ
    # （そうしないと resume のたびに kana_log.txt が歯抜けになり、verify が使えなくなる）。
    old_log, cur = {}, None
    lf = out / "kana_log.txt"
    if resume and lf.exists():
        for ln in lf.read_text(encoding="utf-8").splitlines():
            if ln.startswith("["):
                cur = ln[1:ln.index("]")]
                old_log.setdefault(cur, []).append(ln)
            elif cur:
                old_log[cur].append(ln)
    log_by_cid = {}
    kept = 0
    for cid, lines in SCRIPT:
        sigs[cid] = _sig(lines)
        if (resume and old_sig.get(cid) == sigs[cid]
                and (out / f"{cid}.wav").exists()
                and cid in prev.get("durations", {})
                and cid in old_log):
            durs[cid] = prev["durations"][cid]
            subs[cid] = prev["subtitles"][cid]
            log_by_cid[cid] = old_log[cid]
            kept += 1
            continue
        log = []
        chunks, params, t, rows = [], None, 0.0, []
        for line in lines:
            frames, params, sec, kana = synth(apply_yomi(line))
            rows.append({"t": round(t, 3), "d": round(sec, 3), "text": line})
            if sec > longest[0]:
                longest = (sec, line)
            log += [f"[{cid}] {sec:5.2f}s  {line}", f"         {kana}"]
            for msg in check_kana(cid, line, kana):
                print(msg)
                bad += 1
            chunks.append(frames)
            t += sec + GAP
            chunks.append(b"\x00" * int(GAP * params[2]) * params[1] * params[0])
        total = t - GAP
        with wave.open(str(out / f"{cid}.wav"), "w") as w:
            w.setnchannels(params[0])
            w.setsampwidth(params[1])
            w.setframerate(params[2])
            w.writeframes(b"".join(chunks[:-1]))
        durs[cid] = round(total, 2)
        subs[cid] = rows
        log_by_cid[cid] = log
        print(f"{cid}: {total:5.2f}s  ({len(lines)}行)", flush=True)
    # SCRIPT の順に並べ直して書く（持ち越しぶんと新規ぶんが混ざるため）
    (out / "kana_log.txt").write_text(
        "\n".join(l for cid, _ in SCRIPT for l in log_by_cid.get(cid, [])), encoding="utf-8")
    (out / "narration.json").write_text(
        json.dumps({"speaker": SPEAKER, "speed": SPEED, "credit": CREDIT,
                    "gap": GAP, "durations": durs, "subtitles": subs,
                    "signatures": sigs},
                   ensure_ascii=False, indent=2), encoding="utf-8")
    # 台本から消えたカットの wav が残っていると、次の resume で歯抜けに気づけない
    for f in out.glob("*.wav"):
        if f.stem not in durs:
            f.unlink()
            print(f"（台本から消えた {f.stem}.wav を削除）")
    if resume:
        print(f"\n持ち越し {kept} カット ／ 作り直し {len(SCRIPT) - kept} カット")
    print(f"\n合計 {sum(durs.values()):.1f} 秒")
    print(f"最長の1行 = {longest[0]:.2f}秒「{longest[1]}」")
    if longest[0] > 8.0:
        print("⚠️ 8秒を超える字幕行がある。長すぎるので文を分けること。")
    print("かなログ → audio/kana_log.txt（⑤ 通し確認の前に必ず目で読む）")
    if bad:
        print(f"\n🔴 誤読の疑い {bad} 件。YOMI を直してから作り直すこと。")
        return 1
    print("✓ 禁止パターンの検出なし")
    return 0


