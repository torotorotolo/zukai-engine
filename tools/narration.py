def to_kata(s):
    """ひらがな→カタカナ。**辞書の値は必ずこれを通してからエンジンへ渡す。**

    🔴 2026-07-30 実測で判明した2つの事故が、どちらもこれで直る。
      ① 助詞に読み替えられる … `"18本": "じゅうはちほん"` が **「ジュウワチホン」**になった。
         かなの「は」をエンジンが助詞の「ワ」として解釈していた。
      ② 語中で割れて吃る … `"3,363メートル"` が
         「サンゼンサン／ビャクロクジュウ／サンメエトル」の3つに割れた
         （2026-07-29 の「ナ／ナマン」とまったく同じ型）。
    カタカナは1語として扱われるので、どちらも起きない。
    **辞書はひらがなのまま書いてよい**（人が読めるほうが大事）。変換はここでやる。
    """
    if any("\u4e00" <= c <= "\u9fff" for c in s):
        return s   # 漢字混じりの値はそのまま（例「耐圧かく」。カタカナ化すると割れる）
    return "".join(chr(ord(c) + 0x60) if "ぁ" <= c <= "ゖ" else c for c in s)


# 🔴 2026-08-06：**カタカナ化を通してはいけない値**。
#   `to_kata` は「語を1つにまとめる」ために入れてあるが、それは裏を返すと
#   **ひらがなで書いたときの割れ方を消してしまう**ということでもある。
#   カズヤくんが3案を聴き比べて選んだのは「ひらがなで書いたときの割れ方」のほうなので、
#   ここに入れた語だけは書いたままエンジンへ渡す。
#   ⚠️ 入れる前に必ずエンジンのかな出力で確かめること（値そのものが誤ると
#     5重チェックが全段素通りする＝[[feedback-yomi-dict-must-be-verified]]）。
# 🔴 2026-08-10 追加の2件は、どちらも **カタカナ化すると壊れる**ことを投げて確かめた。
#   "札には" … to_kata で「フダニハ」になり、**「には」が助詞として読まれなくなる**
#              （ひらがなのままなら フダニワ ＝正しい）
#   "次の"   … to_kata で c418 が「ソシテツギノ」と1語に潰れる
#   "22.5パーセント" … to_kata で「ニ／ジュウニテンゴ」＝**2、12.5** に割れる
NO_KATA = {"520人", "その間に", "この間", "札には", "次の", "22.5パーセント"}


def apply_yomi(text):
    """長い語から順に置換する（「737-200型機」が「737-200」に食われないように）。"""
    for k in sorted(YOMI, key=len, reverse=True):
        v = YOMI[k] if k in NO_KATA else to_kata(YOMI[k])
        text = text.replace(k, v)
    return text


def yomi_collisions():
    """★辞書そのものの検査（2026-07-30 追加）。

    `apply_yomi` は長い語から順に置換するが、**短い数詞キーが長い数字列の途中に
    食い込む**事故は防げない。実例：`"2年"` を登録すると `2022年` が
    「202にねん」になる。置換された位置の直前が数字なら、それは食い違いである。
    """
    bad = []
    for _, lines in SCRIPT:
        for line in lines:
            t = line
            for k in sorted(YOMI, key=len, reverse=True):
                i = 0
                while (i := t.find(k, i)) >= 0:
                    if i > 0 and t[i - 1] in "0123456789０-９,.":
                        bad.append(f"🔴 「{k}」が「{t[max(0,i-4):i+len(k)+2]}」の途中に食い込む")
                    i += len(k)
                t = t.replace(k, YOMI[k])
    for b in sorted(set(bad)):
        print(b)
    return len(set(bad))


def lint():
    warn = 0
    for cid, text in ((c, "".join(ls)) for c, ls in SCRIPT):
        spoken = apply_yomi(text)
        hits = []
        for m in NUM_COUNTER.finditer(spoken):
            hits.append(("数詞", m.group(0)))
        for w in RISKY:
            if w in spoken:
                hits.append(("難読", w))
        for kind, s in hits:
            warn += 1
            print(f"{cid}  [要確認] {kind}: 「{s}」")
    print(f"\n{'★要確認 ' + str(warn) + '件 — YOMI に追記するか台本をかな書きに直す' if warn else '✓ 危険語なし'}")
    print("\n── 辞書そのものの検査（数詞キーの食い込み）──")
    c = yomi_collisions()
    print("🔴 食い込み %d 件。YOMI を直すこと。" % c if c else "✓ 食い込みなし")
    return warn + c


def post(path, payload=None, query=""):
    url = f"{BASE}/{path}?{query}"
    data = json.dumps(payload, ensure_ascii=False).encode() if payload is not None else b""
    req = urllib.request.Request(url, data=data, method="POST",
                                 headers={"Content-Type": "application/json"})
    return urllib.request.urlopen(req, timeout=300)


def kana_of(query):
    return "／".join("".join(m["text"] for m in ap["moras"])
                     for ap in query["accent_phrases"])


def chunk(text, dur, limit=2.8):
    """⚠️ **2026-07-30 に使用中止。** 字幕を limit 秒以下に割る処理。

    「3秒以上の静止禁止」を字幕で満たそうとして入れたが、
    **カズヤくん判定で「細かく割りすぎて見にくい」＝不採用**。
    静止禁止は図とグラフの動きで満たすことにした。経緯のために残すが呼ばない。

    （旧説明）字幕を **1枚あたり limit 秒以下** に割る。

    音声は自然な節（読点まで）で合成しているので**そのまま**。
    割るのは表示だけで、尺は文字数比で配分する。
    こうしないと、字幕に合わせて音声を刻むことになり、抑揚が毎回リセットされて棒読みになる。
    """
    parts = [p for p in re.findall(r"[^、。]+[、。]?", text) if p]
    # まだ長い塊は文字数で二分する
    out = []
    for p in parts:
        if dur * len(p) / len(text) <= limit or len(p) < 10:
            out.append(p)
            continue
        n = int(dur * len(p) / len(text) / limit) + 1
        step = -(-len(p) // n)
        out += [p[i:i + step] for i in range(0, len(p), step)]
    total = sum(len(p) for p in out)
    rows, t = [], 0.0
    for p in out:
        d = dur * len(p) / total
        rows.append({"t": round(t, 3), "d": round(d, 3), "text": p})
        t += d
    return rows


def resub():
    """音声は作り直さず、**字幕の割り方だけ**やり直す。"""
    p = HERE / "audio" / "narration.json"
    d = json.loads(p.read_text(encoding="utf-8"))
    lines = dict(SCRIPT)
    worst = (0.0, "")
    for cid, rows in d["subtitles"].items():
        new, t = [], 0.0
        for r in rows:
            for c in chunk(r["text"], r["d"]):
                new.append({"t": round(r["t"] + c["t"], 3), "d": c["d"], "text": c["text"]})
                if c["d"] > worst[0]:
                    worst = (c["d"], c["text"])
        d["subtitles"][cid] = new
        print(f"{cid}: {len(rows)}行 → {len(new)}枚")
    p.write_text(json.dumps(d, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"\n最長の字幕 = {worst[0]:.2f}秒「{worst[1]}」")
    print("✓ 3秒以下" if worst[0] <= 3.0 else "🔴 まだ3秒を超えている")
    return 0 if worst[0] <= 3.0 else 1


def kana():
    """★合成せずに読みだけ確かめる（2026-07-30 追加）。

    `audio_query` は読み（accent_phrases）を返すだけで、音声は作らない。
    **1本ぶんの合成は2〜3時間かかる**ので、誤読はここで全部潰してから build する。
    出力は `audio/kana_dry.txt`。FORBIDDEN に当たった行はその場で赤く出す。
    """
    out = HERE / "audio"
    out.mkdir(exist_ok=True)
    log, bad, n = [], 0, 0
    for cid, lines in SCRIPT:
        for line in lines:
            spoken = apply_yomi(line)
            q = json.loads(post("audio_query", None,
                                f"speaker={SPEAKER}&text={urllib.parse.quote(spoken)}").read())
            k = kana_of(q)
            n += 1
            log.append(f"[{cid}] {line}\n         {k}")
            for msg in check_kana(cid, line, k):
                print(msg, flush=True)
                bad += 1
            if n % 25 == 0:
                print(f"  ... {n}行", flush=True)
    (out / "kana_dry.txt").write_text("\n".join(log), encoding="utf-8")
    print(f"\n{n}行の読みを取得 → audio/kana_dry.txt")
    if bad:
        print(f"🔴 禁止パターン {bad} 件。YOMI を直してから build すること。")
        return 1
    print("✓ 禁止パターンの検出なし（⚠️ これは自動判定ぶんだけ。目でも読むこと）")
    return 0


def verify():
    """★生成が終わったあと、`audio/kana_log.txt` を後から機械照合する（2026-07-31 追加）。

    `build` の警告は標準出力にしか出ないので、**ログを取り逃すと検証できない**
    （実際に Tee-Object のロックで1本ぶん流した）。kana_log.txt はディスクに残るので、
    そこから④の照合をやり直せるようにした。wav の本数と尺も併せて確認する。
    """
    a = HERE / "audio"
    log = a / "kana_log.txt"
    if not log.exists():
        print("🔴 audio/kana_log.txt が無い。build が最後まで通っていない。")
        return 1
    rows, bad = [], 0
    lines = log.read_text(encoding="utf-8").splitlines()
    for i in range(0, len(lines) - 1, 2):
        head, kana = lines[i], lines[i + 1].strip()
        if not head.startswith("["):
            continue
        cid = head[1:head.index("]")]
        text = head.split("  ", 2)[-1]
        rows.append(cid)
        for msg in check_kana(cid, text, kana):
            print(msg)
            bad += 1
    want = [c for c, _ in SCRIPT]
    wav = sorted(p.stem for p in a.glob("*.wav"))
    missing = [c for c in want if c not in wav]
    print(f"\nかなログ {len(rows)}行 ／ 台本 {sum(len(l) for _, l in SCRIPT)}行")
    print(f"wav {len(wav)} / {len(want)} カット" + (f"  🔴 未生成: {missing[:8]}" if missing else "  ✓ 全カットそろっている"))
    if (a / "narration.json").exists():
        d = json.loads((a / "narration.json").read_text(encoding="utf-8"))
        t = sum(d["durations"].values())
        print(f"合計 {t:.1f}秒 = {t/60:.1f}分（発話のみ）")
    if bad:
        print(f"🔴 誤読の疑い {bad} 件。")
        return 1
    print("✓ 機械照合は通過（⑤ 耳での通し確認はこのあと）")
    return 0 if not missing else 1


def synth(text):
    """1行ぶんを合成して (wavバイト列, 秒, かな) を返す。"""
    q = json.loads(post("audio_query", None,
                        f"speaker={SPEAKER}&text={urllib.parse.quote(text)}").read())
    q["speedScale"] = SPEED
    wav = post("synthesis", q, f"speaker={SPEAKER}").read()
    import io
    with wave.open(io.BytesIO(wav)) as w:
        sec = w.getnframes() / w.getframerate()
        p = (w.getnchannels(), w.getsampwidth(), w.getframerate())
        frames = w.readframes(w.getnframes())
    return frames, p, sec, kana_of(q)


def _sig(lines):
    """カットの内容の指紋。1文字でも変われば別物として作り直す。"""
    # 🔴 2026-08-01 修正。**台本の生の文字だけを見ていたのが誤りだった。**
    #    エンジンへ渡るのは apply_yomi() を通したあとの文字列なので、
    #    **台本が同じでも YOMI を直せば音は変わる**。ところが指紋は変わらないため
    #    `build resume` が「変更なし」と判断し、**古い音声をそのまま残していた。**
    #    2026-08-01、`潜らせた` と `2.25` の読みを直したときに実際に踏んだ
    #    （直したつもりで、古い音のまま焼くところだった）。
    #    → 指紋は**実際にエンジンへ渡る文字列**から取る。
    import hashlib
    spoken = "".join(apply_yomi(x) for x in lines)
    return hashlib.sha1((spoken + f"|{SPEAKER}|{SPEED}|{GAP}").encode()).hexdigest()[:12]


def build(resume=False):
    """resume=True なら**内容が変わっていないカットの wav を作り直さない**。

    🔴 2026-07-31 追加。1本ぶんの合成は30分かかるので、台本を1行直すたびに
    30分待つのは現実的でない。`narration.json` に各カットの指紋を書いておき、
    指紋が一致して wav も残っているカットは、前回の尺と字幕をそのまま持ち越す。
    """
    out = HERE / "audio"
    out.mkdir(exist_ok=True)
    prev, old_sig = {}, {}
    if resume and (out / "narration.json").exists():
        prev = json.loads((out / "narration.json").read_text(encoding="utf-8"))
        old_sig = prev.get("signatures", {})
    durs, subs, sigs, bad, longest = {}, {}, {}, 0, (0.0, "")
    # かなログも持ち越す。作り直したカットだけ新しくして、残りは前回の記録を引き継ぐ
    # （そうしないと resume のたびに kana_log.txt が歯抜けになり、verify が使えなくなる）。
    old_log, cur = {}, None
    lf = out / "kana_log.txt"
    if resume and lf.exists():
        for ln in lf.read_text(encoding="utf-8").splitlines():
            if ln.startswith("["):
                cur = ln[1:ln.index("]")]
                old_log.setdefault(cur, []).append(ln)
            elif cur:
                old_log[cur].append(ln)
    log_by_cid = {}
    kept = 0
    for cid, lines in SCRIPT:
        sigs[cid] = _sig(lines)
        if (resume and old_sig.get(cid) == sigs[cid]
                and (out / f"{cid}.wav").exists()
                and cid in prev.get("durations", {})
                and cid in old_log):
            durs[cid] = prev["durations"][cid]
            subs[cid] = prev["subtitles"][cid]
            log_by_cid[cid] = old_log[cid]
            kept += 1
            continue
        log = []
        chunks, params, t, rows = [], None, 0.0, []
        for line in lines:
            frames, params, sec, kana = synth(apply_yomi(line))
            rows.append({"t": round(t, 3), "d": round(sec, 3), "text": line})
            if sec > longest[0]:
                longest = (sec, line)
            log += [f"[{cid}] {sec:5.2f}s  {line}", f"         {kana}"]
            for msg in check_kana(cid, line, kana):
                print(msg)
                bad += 1
            chunks.append(frames)
            t += sec + GAP
            chunks.append(b"\x00" * int(GAP * params[2]) * params[1] * params[0])
        total = t - GAP
        with wave.open(str(out / f"{cid}.wav"), "w") as w:
            w.setnchannels(params[0])
            w.setsampwidth(params[1])
            w.setframerate(params[2])
            w.writeframes(b"".join(chunks[:-1]))
        durs[cid] = round(total, 2)
        subs[cid] = rows
        log_by_cid[cid] = log
        print(f"{cid}: {total:5.2f}s  ({len(lines)}行)", flush=True)
    # SCRIPT の順に並べ直して書く（持ち越しぶんと新規ぶんが混ざるため）
    (out / "kana_log.txt").write_text(
        "\n".join(l for cid, _ in SCRIPT for l in log_by_cid.get(cid, [])), encoding="utf-8")
    (out / "narration.json").write_text(
        json.dumps({"speaker": SPEAKER, "speed": SPEED, "credit": CREDIT,
                    "gap": GAP, "durations": durs, "subtitles": subs,
                    "signatures": sigs},
                   ensure_ascii=False, indent=2), encoding="utf-8")
    # 台本から消えたカットの wav が残っていると、次の resume で歯抜けに気づけない
    for f in out.glob("*.wav"):
        if f.stem not in durs:
            f.unlink()
            print(f"（台本から消えた {f.stem}.wav を削除）")
    if resume:
        print(f"\n持ち越し {kept} カット ／ 作り直し {len(SCRIPT) - kept} カット")
    print(f"\n合計 {sum(durs.values()):.1f} 秒")
    print(f"最長の1行 = {longest[0]:.2f}秒「{longest[1]}」")
    if longest[0] > 8.0:
        print("⚠️ 8秒を超える字幕行がある。長すぎるので文を分けること。")
    print("かなログ → audio/kana_log.txt（⑤ 通し確認の前に必ず目で読む）")
    if bad:
        print(f"\n🔴 誤読の疑い {bad} 件。YOMI を直してから作り直すこと。")
        return 1
    print("✓ 禁止パターンの検出なし")
    return 0


