        hits = []
        for m in NUM_COUNTER.finditer(spoken):
            hits.append(("数詞", m.group(0)))
        for w in RISKY:
            if w in spoken:
                hits.append(("難読", w))
        for kind, s in hits:
            warn += 1
            print(f"{cid}  [要確認] {kind}: 「{s}」")
