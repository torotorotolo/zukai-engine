def synth(text):
    """1行ぶんを合成して (wavバイト列, 秒, かな) を返す。"""
    q = json.loads(post("audio_query", None,
                        f"speaker={SPEAKER}&text={urllib.parse.quote(text)}").read())
    q["speedScale"] = SPEED
    wav = post("synthesis", q, f"speaker={SPEAKER}").read()
    import io
    with wave.open(io.BytesIO(wav)) as w:
        sec = w.getnframes() / w.getframerate()
        p = (w.getnchannels(), w.getsampwidth(), w.getframerate())
        frames = w.readframes(w.getnframes())
    return frames, p, sec, kana_of(q)


def _sig(lines):
    """カットの内容の指紋。1文字でも変われば別物として作り直す。"""
    # 🔴 2026-08-01 修正。**台本の生の文字だけを見ていたのが誤りだった。**
    #    エンジンへ渡るのは apply_yomi() を通したあとの文字列なので、
    #    **台本が同じでも YOMI を直せば音は変わる**。ところが指紋は変わらないため
    #    `build resume` が「変更なし」と判断し、**古い音声をそのまま残していた。**
    #    2026-08-01、`潜らせた` と `2.25` の読みを直したときに実際に踏んだ
    #    （直したつもりで、古い音のまま焼くところだった）。
    #    → 指紋は**実際にエンジンへ渡る文字列**から取る。
    import hashlib
    spoken = "".join(apply_yomi(x) for x in lines)
    return hashlib.sha1((spoken + f"|{SPEAKER}|{SPEED}|{GAP}").encode()).hexdigest()[:12]


