def check_kana(cid, line, k):
    """④ の機械照合。FORBIDDEN は区切り込み、EXPECT は区切りを外して見る。"""
    flat = k.replace("／", "")
    bad = []
    for ng, why in FORBIDDEN.items():
        if ng in k:
            bad.append(f"🔴 {cid}「{line}」: {why}（{ng}）")
    for mora, word in EXPECT.items():
        if word in line and mora not in flat:
            bad.append(f"🔴 {cid}「{line}」: 「{word}」が {mora} と読まれていない")
    return bad

