def to_kata(s):
    """ひらがな→カタカナ。**辞書の値は必ずこれを通してからエンジンへ渡す。**

    🔴 2026-07-30 実測で判明した2つの事故が、どちらもこれで直る。
      ① 助詞に読み替えられる … `"18本": "じゅうはちほん"` が **「ジュウワチホン」**になった。
         かなの「は」をエンジンが助詞の「ワ」として解釈していた。
      ② 語中で割れて吃る … `"3,363メートル"` が
         「サンゼンサン／ビャクロクジュウ／サンメエトル」の3つに割れた
         （2026-07-29 の「ナ／ナマン」とまったく同じ型）。
    カタカナは1語として扱われるので、どちらも起きない。
    **辞書はひらがなのまま書いてよい**（人が読めるほうが大事）。変換はここでやる。
    """
    if any("\u4e00" <= c <= "\u9fff" for c in s):
        return s   # 漢字混じりの値はそのまま（例「耐圧かく」。カタカナ化すると割れる）
    return "".join(chr(ord(c) + 0x60) if "ぁ" <= c <= "ゖ" else c for c in s)


# 🔴 2026-08-06：**カタカナ化を通してはいけない値**。
#   `to_kata` は「語を1つにまとめる」ために入れてあるが、それは裏を返すと
#   **ひらがなで書いたときの割れ方を消してしまう**ということでもある。
#   カズヤくんが3案を聴き比べて選んだのは「ひらがなで書いたときの割れ方」のほうなので、
#   ここに入れた語だけは書いたままエンジンへ渡す。
#   ⚠️ 入れる前に必ずエンジンのかな出力で確かめること（値そのものが誤ると
#     5重チェックが全段素通りする＝[[feedback-yomi-dict-must-be-verified]]）。
# 🔴 2026-08-10 追加の2件は、どちらも **カタカナ化すると壊れる**ことを投げて確かめた。
#   "札には" … to_kata で「フダニハ」になり、**「には」が助詞として読まれなくなる**
#              （ひらがなのままなら フダニワ ＝正しい）
#   "次の"   … to_kata で c418 が「ソシテツギノ」と1語に潰れる
#   "22.5パーセント" … to_kata で「ニ／ジュウニテンゴ」＝**2、12.5** に割れる
NO_KATA = {"520人", "その間に", "この間", "札には", "次の", "22.5パーセント"}


def apply_yomi(text):
    """長い語から順に置換する（「737-200型機」が「737-200」に食われないように）。"""
    for k in sorted(YOMI, key=len, reverse=True):
        v = YOMI[k] if k in NO_KATA else to_kata(YOMI[k])
        text = text.replace(k, v)
    return text


def yomi_collisions():
    """★辞書そのものの検査（2026-07-30 追加）。

    `apply_yomi` は長い語から順に置換するが、**短い数詞キーが長い数字列の途中に
    食い込む**事故は防げない。実例：`"2年"` を登録すると `2022年` が
    「202にねん」になる。置換された位置の直前が数字なら、それは食い違いである。
    """
    bad = []
    for _, lines in SCRIPT:
        for line in lines:
            t = line
            for k in sorted(YOMI, key=len, reverse=True):
                i = 0
                while (i := t.find(k, i)) >= 0:
                    if i > 0 and t[i - 1] in "0123456789０-９,.":
                        bad.append(f"🔴 「{k}」が「{t[max(0,i-4):i+len(k)+2]}」の途中に食い込む")
                    i += len(k)
                t = t.replace(k, YOMI[k])
    for b in sorted(set(bad)):
        print(b)
    return len(set(bad))


