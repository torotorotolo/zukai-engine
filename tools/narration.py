def to_kata(s):
    """ひらがな→カタカナ。**辞書の値は必ずこれを通してからエンジンへ渡す。**

    🔴 2026-07-30 実測で判明した2つの事故が、どちらもこれで直る。
      ① 助詞に読み替えられる … `"18本": "じゅうはちほん"` が **「ジュウワチホン」**になった。
         かなの「は」をエンジンが助詞の「ワ」として解釈していた。
      ② 語中で割れて吃る … `"3,363メートル"` が
         「サンゼンサン／ビャクロクジュウ／サンメエトル」の3つに割れた
         （2026-07-29 の「ナ／ナマン」とまったく同じ型）。
    カタカナは1語として扱われるので、どちらも起きない。
    **辞書はひらがなのまま書いてよい**（人が読めるほうが大事）。変換はここでやる。
    """
    if any("\u4e00" <= c <= "\u9fff" for c in s):
        return s   # 漢字混じりの値はそのまま（例「耐圧かく」。カタカナ化すると割れる）
    return "".join(chr(ord(c) + 0x60) if "ぁ" <= c <= "ゖ" else c for c in s)


# 🔴 2026-08-06：**カタカナ化を通してはいけない値**。
#   `to_kata` は「語を1つにまとめる」ために入れてあるが、それは裏を返すと
#   **ひらがなで書いたときの割れ方を消してしまう**ということでもある。
#   カズヤくんが3案を聴き比べて選んだのは「ひらがなで書いたときの割れ方」のほうなので、
#   ここに入れた語だけは書いたままエンジンへ渡す。
#   ⚠️ 入れる前に必ずエンジンのかな出力で確かめること（値そのものが誤ると
#     5重チェックが全段素通りする＝[[feedback-yomi-dict-must-be-verified]]）。
# 🔴 2026-08-10 追加の2件は、どちらも **カタカナ化すると壊れる**ことを投げて確かめた。
#   "札には" … to_kata で「フダニハ」になり、**「には」が助詞として読まれなくなる**
#              （ひらがなのままなら フダニワ ＝正しい）
#   "次の"   … to_kata で c418 が「ソシテツギノ」と1語に潰れる
#   "22.5パーセント" … to_kata で「ニ／ジュウニテンゴ」＝**2、12.5** に割れる
NO_KATA = {"520人", "その間に", "この間", "札には", "次の", "22.5パーセント"}


def apply_yomi(text):
    """長い語から順に置換する（「737-200型機」が「737-200」に食われないように）。"""
    for k in sorted(YOMI, key=len, reverse=True):
        v = YOMI[k] if k in NO_KATA else to_kata(YOMI[k])
        text = text.replace(k, v)
    return text


def yomi_collisions():
    """★辞書そのものの検査（2026-07-30 追加）。

    `apply_yomi` は長い語から順に置換するが、**短い数詞キーが長い数字列の途中に
    食い込む**事故は防げない。実例：`"2年"` を登録すると `2022年` が
    「202にねん」になる。置換された位置の直前が数字なら、それは食い違いである。
    """
    bad = []
    for _, lines in SCRIPT:
        for line in lines:
            t = line
            for k in sorted(YOMI, key=len, reverse=True):
                i = 0
                while (i := t.find(k, i)) >= 0:
                    if i > 0 and t[i - 1] in "0123456789０-９,.":
                        bad.append(f"🔴 「{k}」が「{t[max(0,i-4):i+len(k)+2]}」の途中に食い込む")
                    i += len(k)
                t = t.replace(k, YOMI[k])
    for b in sorted(set(bad)):
        print(b)
    return len(set(bad))


def lint():
    warn = 0
    for cid, text in ((c, "".join(ls)) for c, ls in SCRIPT):
        spoken = apply_yomi(text)
        hits = []
        for m in NUM_COUNTER.finditer(spoken):
            hits.append(("数詞", m.group(0)))
        for w in RISKY:
            if w in spoken:
                hits.append(("難読", w))
        for kind, s in hits:
            warn += 1
            print(f"{cid}  [要確認] {kind}: 「{s}」")
    print(f"\n{'★要確認 ' + str(warn) + '件 — YOMI に追記するか台本をかな書きに直す' if warn else '✓ 危険語なし'}")
    print("\n── 辞書そのものの検査（数詞キーの食い込み）──")
    c = yomi_collisions()
    print("🔴 食い込み %d 件。YOMI を直すこと。" % c if c else "✓ 食い込みなし")
    return warn + c


def post(path, payload=None, query=""):
    url = f"{BASE}/{path}?{query}"
    data = json.dumps(payload, ensure_ascii=False).encode() if payload is not None else b""
    req = urllib.request.Request(url, data=data, method="POST",
                                 headers={"Content-Type": "application/json"})
    return urllib.request.urlopen(req, timeout=300)


def kana_of(query):
    return "／".join("".join(m["text"] for m in ap["moras"])
                     for ap in query["accent_phrases"])


def chunk(text, dur, limit=2.8):
    """⚠️ **2026-07-30 に使用中止。** 字幕を limit 秒以下に割る処理。

    「3秒以上の静止禁止」を字幕で満たそうとして入れたが、
    **カズヤくん判定で「細かく割りすぎて見にくい」＝不採用**。
    静止禁止は図とグラフの動きで満たすことにした。経緯のために残すが呼ばない。

    （旧説明）字幕を **1枚あたり limit 秒以下** に割る。

    音声は自然な節（読点まで）で合成しているので**そのまま**。
    割るのは表示だけで、尺は文字数比で配分する。
    こうしないと、字幕に合わせて音声を刻むことになり、抑揚が毎回リセットされて棒読みになる。
    """
    parts = [p for p in re.findall(r"[^、。]+[、。]?", text) if p]
    # まだ長い塊は文字数で二分する
    out = []
    for p in parts:
        if dur * len(p) / len(text) <= limit or len(p) < 10:
            out.append(p)
            continue
        n = int(dur * len(p) / len(text) / limit) + 1
        step = -(-len(p) // n)
        out += [p[i:i + step] for i in range(0, len(p), step)]
    total = sum(len(p) for p in out)
    rows, t = [], 0.0
    for p in out:
        d = dur * len(p) / total
        rows.append({"t": round(t, 3), "d": round(d, 3), "text": p})
        t += d
    return rows


def resub():
    """音声は作り直さず、**字幕の割り方だけ**やり直す。"""
    p = HERE / "audio" / "narration.json"
    d = json.loads(p.read_text(encoding="utf-8"))
    lines = dict(SCRIPT)
    worst = (0.0, "")
    for cid, rows in d["subtitles"].items():
        new, t = [], 0.0
        for r in rows:
            for c in chunk(r["text"], r["d"]):
                new.append({"t": round(r["t"] + c["t"], 3), "d": c["d"], "text": c["text"]})
                if c["d"] > worst[0]:
                    worst = (c["d"], c["text"])
        d["subtitles"][cid] = new
        print(f"{cid}: {len(rows)}行 → {len(new)}枚")
    p.write_text(json.dumps(d, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"\n最長の字幕 = {worst[0]:.2f}秒「{worst[1]}」")
    print("✓ 3秒以下" if worst[0] <= 3.0 else "🔴 まだ3秒を超えている")
    return 0 if worst[0] <= 3.0 else 1


def kana():
    """★合成せずに読みだけ確かめる（2026-07-30 追加）。

    `audio_query` は読み（accent_phrases）を返すだけで、音声は作らない。
    **1本ぶんの合成は2〜3時間かかる**ので、誤読はここで全部潰してから build する。
    出力は `audio/kana_dry.txt`。FORBIDDEN に当たった行はその場で赤く出す。
    """
    out = HERE / "audio"
    out.mkdir(exist_ok=True)
    log, bad, n = [], 0, 0
    for cid, lines in SCRIPT:
        for line in lines:
            spoken = apply_yomi(line)
            q = json.loads(post("audio_query", None,
                                f"speaker={SPEAKER}&text={urllib.parse.quote(spoken)}").read())
            k = kana_of(q)
            n += 1
            log.append(f"[{cid}] {line}\n         {k}")
            for msg in check_kana(cid, line, k):
                print(msg, flush=True)
                bad += 1
