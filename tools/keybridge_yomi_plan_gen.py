def suspect_lids():
    """🔴 A/B は「実際に崩れた行」で試す。何ともなかった行で試すと『変わらず』しか出ない
    （＝候補の可否が決まらないまま、決まったつもりになる）。順位は 読みが違う → 判定できない → 所見あり。"""
    rank = {}
    p = ES.qa_path("reading_diff.tsv")
    if p.exists():
        for l in p.read_text(encoding="utf-8").splitlines()[1:]:
            f = l.split("\t")
            if len(f) >= 2:
                rank[f[0]] = {"読みが違う": 0, "判定できない": 1}.get(f[1], 2)
    return rank


def main():
    by_key = {}
    lines = ES.lines()
    rank = suspect_lids()
    plan, miss = [], []
    for cand in CAND:
        key, val, why = cand[:3]
        want = cand[3] if len(cand) > 3 else None
        hit = [l for l in lines if key in l.text]
        if not hit:
            miss.append(key)
            continue
        by_key[key] = len(hit)
        pick = ([l for l in hit if l.lid == want] or
                sorted(hit, key=lambda l: (rank.get(l.lid, 3), lines.index(l))))[0]
        if want and pick.lid != want:
            raise SystemExit(f'🔴 指定した行にキーが無い: {want} / {key}')
        plan.append({"id": pick.lid, "key": key, "val": val, "why": why})
    for key, n in by_key.items():
        print(f"  {key:<12} {n:>3}行  → {plan[[p['key'] for p in plan].index(key)]['id']}")
    if miss:
        raise SystemExit(f"🔴 台本に当たらない候補（書き損じ）: {miss}")
    print(f"\n候補 {len(plan)}件／当たる行 のべ {sum(by_key.values())}")
    if "--dry" in sys.argv:
        return 0
    p = Path(__file__).resolve().parent / "keybridge_yomi_plan.json"
    p.write_text(json.dumps(plan, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"-> {p}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
